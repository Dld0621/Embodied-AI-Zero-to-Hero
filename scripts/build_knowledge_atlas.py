            data_table(atom["visual"]),
            "### 容易混淆的地方",
            f"**常见误解：**{atom['misconception']['wrong']}",
            f"**为什么不成立：**{atom['misconception']['why']}",
            f"**正确理解：**{atom['misconception']['right']}",
            "### 自测",
            atom["check"]["question"],
