            "\n".join(f"{i + 1}. {step}" for i, step in enumerate(atom["mechanism"])),
            "### 手算或追踪一个例子",
            "\n".join(f"{i + 1}. {step}" for i, step in enumerate(atom["worked_example"])),
            "### 用图理解",
